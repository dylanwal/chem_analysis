def bin_mass(data: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    mz = data[:, 0].astype(int)
    mz_final = np.unique(mz)
    abs_final = np.zeros_like(mz_final)
    for row in data:
        for i in range(len(abs_final)):
            if int(row[0]) == mz_final[i]:
                abs_final[i] += row[1]

    return mz_final, abs_final


def main():
    x, y = bin_mass(time_zero_raw)
    ms = ca.mass_spec.ms_signal.MSSignal(x, y, name="0 min")
    x, y = bin_mass(final_time_raw)
    ms_final = ca.mass_spec.ms_signal.MSSignal(x, y, name="120 min")
    x, y = bin_mass(no_d)
    ms_no_d = ca.mass_spec.ms_signal.MSSignal(x, y, name="ketone with H")

    fig = ca.plot.signal(ms, normalize=1)
    fig = ca.plot.signal(ms_final, fig=fig, normalize=1)
    fig = ca.plot.signal(ms_no_d, fig=fig, normalize=1)

    fig.layout.xaxis.title.font = {'size': 20}
    fig.layout.xaxis.tickfont = {'size': 20}
    fig.layout.yaxis.title.font = {'size': 20}
    fig.layout.yaxis.tickfont = {'size': 20}
    fig.layout.legend.font = {'size': 20}
    fig.show("browser")


if __name__ == "__main__":
    main()
